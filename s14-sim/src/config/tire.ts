/**
 * ПАРАМЕТРЫ МОДЕЛИ ШИНЫ (Magic Formula + пневматический трейл + давление).
 *
 * Все коэффициенты — [предположение]: типовые для 245/40R18 уличного/дрифт-класса.
 * Для реальных выводов шину нужно калибровать по данным производителя или тестам
 * (особенно знак и угол нуля пневматического трейла: tBu*, tCt).
 * Формулы и смысл каждого коэффициента — в src/physics/tire.ts.
 */

export interface TireParams {
  /** Опорные условия, к которым привязаны коэффициенты. */
  Fz0: number; // Н, номинальная нагрузка
  p0: number; // бар, опорное давление

  /** Пик сцепления. */
  mu0: number; // коэффициент трения при Fz0, p0
  muLoadSens: number; // dμ при +100 % нагрузки (отрицательно: сцепление падает с нагрузкой)
  muPressSens: number; // dμ/μ при +100 % давления (падение пика из-за меньшего пятна)
  muCamberK: number; // потеря пика на 1° развала²

  /** Жёсткость при увод. */
  c1: number; // Cα,max / Fz0, 1/рад
  c2: number; // нагрузка максимума жёсткости, в долях Fz0
  stiffPressSens: number; // dCα/Cα при +100 % давления

  /** Форма кривой Fy. */
  Cy: number;
  Ey: number;
  /** Камбер-тяга: Cγ / Cα (эквивалентный угол увода на 1 рад развала). */
  camberStiffRatio: number;

  /** Круг трения: μx/μy. */
  muXRatio: number;

  /** Пятно контакта. */
  carcassPressureBar: number; // добавка к давлению накачки — жёсткость каркаса
  patchWidthRatio: number; // ширина пятна / ширина протектора

  /** Пневматический трейл. */
  trailPatchK: number; // t0 = trailPatchK · длина пятна
  trailBu: number; // масштаб по α/αsl
  trailCt: number; // >1: трейл меняет знак
  trailEt: number;
}

